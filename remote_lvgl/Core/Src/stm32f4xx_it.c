/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
   // 检测 IDLE 中断
  if (__HAL_UART_GET_FLAG(&huart3, UART_FLAG_IDLE) != RESET)
  {
    __HAL_UART_CLEAR_IDLEFLAG(&huart3);

    // 1. 计算当前 DMA 头指针位置
    uint16_t current_pos = RX_BUF_SIZE - __HAL_DMA_GET_COUNTER(&hdma_usart3_rx);

    // 2. 计算接收到的数据长度
    // 既然进了 IDLE 中断，说明收到了一段数据
    if (current_pos != last_dma_pos)
    {
        UartPacket_t packet;
        packet.len = 0;

        // 情况 A: 没有卷回 (线性)
        // [.......Last>>>>Current.......]
        if (current_pos > last_dma_pos)
        {
            packet.len = current_pos - last_dma_pos;
            if (packet.len <= 64) // 防止溢出结构体
            {
                memcpy(packet.data, &rx_buffer[last_dma_pos], packet.len);
            }
        }
        // 情况 B: 卷回了 (分两段)
        // [>>Current...........Last>>>>>]
        else
        {
            uint16_t tail_len = RX_BUF_SIZE - last_dma_pos; // 尾部长度
            uint16_t head_len = current_pos;                // 头部长度
            packet.len = tail_len + head_len;

            if (packet.len <= 64)
            {
                // 先拷尾部
                memcpy(packet.data, &rx_buffer[last_dma_pos], tail_len);
                // 再拷头部 (拼接到后面)
                memcpy(&packet.data[tail_len], &rx_buffer[0], head_len);
            }
        }

        // 3. 发送给队列 (Timeout=0, ISR专用)
        // 只有长度合法才发
        if (packet.len > 0 && packet.len <= 64)
        {
            osMessageQueuePut(uartRxQueueHandle, &packet, 0, 0);
        }

        // 4. 更新位置
        last_dma_pos = current_pos;
    }
  }
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

