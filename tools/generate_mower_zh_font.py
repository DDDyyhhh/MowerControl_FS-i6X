#!/usr/bin/env python3
"""Generate the fixed 12px UI bitmap subset from OFL Noto Sans Mono CJK SC.

Run with a Pillow-enabled Python. Font URL, SHA256 and license live alongside
the generated header. The firmware build uses that checked-in header only.
"""
import argparse
import hashlib
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
gui = root / 'OpenI6X/FS-I6X/opentx/radio/src/gui/128x64'
parser = argparse.ArgumentParser()
parser.add_argument('font', type=Path)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 12)
# Include literal text plus numeric/hex digits used by formatted values.
source = (gui / 'mower_user_ui.h').read_text()
view = (gui / 'view_main.cpp').read_text()
source += view[view.index('static void mowerExp3Overlay('):view.index('static void mowerPage(')]
source = re.sub(r'^#include.*$', '', source, flags=re.M)
strings = re.findall(r'"([^"\n]*)"', source)
codes = sorted(set(map(ord, '0123456789ABCDEFabcdef')) |
               {ord(c) for s in strings for c in s if 32 <= ord(c) < 127 or '\u4e00' <= c <= '\u9fff'})
bits, records = [], []
for code in codes:
    width = 6 if code < 128 else 12
    image = Image.new('L', (width, 12))
    ImageDraw.Draw(image).text((0, 10), chr(code), font=font, fill=255, anchor='ls')
    packed = [0] * ((width * 12 + 7) // 8)
    for y in range(12):
        for x in range(width):
            if image.getpixel((x, y)) >= 80:
                bit = y * width + x
                packed[bit // 8] |= 1 << (bit % 8)
    if code != 32:
        assert any(packed), f'Missing glyph {chr(code)}'
    records.append(f'  {{0x{code:04X}, {len(bits)}}}, // U+{code:04X}')
    bits.extend(packed)
digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
out = ['#pragma once', '// Generated by tools/generate_mower_zh_font.py; do not edit.',
       '// Derived font: Mower UI Subset 12. Noto source under SIL OFL 1.1.',
       f'// Source SHA256: {digest}', '#include <stdint.h>',
       'struct MowerZhGlyph { uint16_t code; uint16_t offset; };',
       'static const MowerZhGlyph mowerZhGlyphs[] = {', *records, '};',
       'static const uint8_t mowerZhBits[] = {']
for i in range(0, len(bits), 16):
    out.append('  ' + ', '.join(f'0x{b:02X}' for b in bits[i:i+16]) + ',')
out += ['};', '']
(gui / 'mower_zh_font.h').write_text('\n'.join(out))
print(f'{len(codes)} glyphs; {len(bits)} bitmap bytes; source SHA256 {digest}')
