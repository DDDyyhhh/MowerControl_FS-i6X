#!/usr/bin/env python3
"""Generate the fixed 11px UI bitmap subset from OFL Noto Sans Mono CJK SC.

Run with a Pillow-enabled Python. Font URL, SHA256 and license live alongside
the generated header. The firmware build uses that checked-in header only.
"""
import argparse
import hashlib
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
gui = root / 'OpenI6X/FS-I6X/opentx/radio/src/gui/128x64'
parser = argparse.ArgumentParser()
parser.add_argument('font', type=Path)
parser.add_argument('--font-index', type=int, default=0,
                    help='face index when the source is a TTC collection')
parser.add_argument('--check', action='store_true',
                    help='verify the checked-in header without rewriting it')
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 11, index=args.font_index)
if font.getname() != ('Noto Sans Mono CJK SC', 'Regular'):
    parser.error('Expected Noto Sans Mono CJK SC Regular')
height, ascii_width, cjk_width, cjk_bitmap_height = 12, 6, 11, 11
# Retain the production literals, decimal/hex digits and numeric punctuation.
# Native experimental overlays use the native LCD font, not this bitmap subset.
source = (gui / 'mower_user_ui.h').read_text()
view = (gui / 'view_main.cpp').read_text()
overlay = view[view.index('static void mowerExp3Overlay('):view.index('static void mowerPage(')]
source += overlay.split('\n#else\n', 1)[0]
source = re.sub(r'^\s*#.*$', '', source, flags=re.M)
strings = re.findall(r'"([^"\n]*)"', source)
codes = sorted({ord(c) for c in '0123456789ABCDEF +-.%'} |
               {ord(c) for s in strings for c in s if 32 <= ord(c) < 127 or '\u4e00' <= c <= '\u9fff'})
ascii_count = sum(code < 128 for code in codes)
bits, records = [], []
for code in codes:
    width = ascii_width if code < 128 else cjk_width
    bitmap_height = height if code < 128 else cjk_bitmap_height
    # CJK needs the top row; ASCII descenders (g/j/p/q/y/|) need the bottom.
    baseline = 9 if code < 128 else 10
    image = Image.new('L', (width, bitmap_height))
    ImageDraw.Draw(image).text((0, baseline), chr(code), font=font, fill=255, anchor='ls')
    image = image.point(lambda value: 255 if value >= 80 else 0)
    # Render outside the cell too: nonempty glyphs alone do not detect cropping.
    reference = Image.new('L', (40, 40))
    ImageDraw.Draw(reference).text((10, 20), chr(code), font=font, fill=255, anchor='ls')
    reference = reference.point(lambda value: 255 if value >= 80 else 0)
    bounds = reference.getbbox()
    if bounds:
        left, top, right, bottom = bounds
        assert left >= 10 and right <= 10 + width, f'Horizontal crop: U+{code:04X}'
        assert top >= 20 - baseline and bottom <= 20 - baseline + bitmap_height, \
            f'Vertical crop: U+{code:04X}'
    assert image.histogram()[255] == reference.histogram()[255], f'Lost pixels: U+{code:04X}'
    packed = [0] * ((width * bitmap_height + 7) // 8)
    for y in range(bitmap_height):
        for x in range(width):
            if image.getpixel((x, y)):
                bit = y * width + x
                packed[bit // 8] |= 1 << (bit % 8)
    if code != 32:
        assert any(packed), f'Missing glyph {chr(code)}'
    records.append(f'  {{0x{code:04X}}}, // U+{code:04X}')
    bits.extend(packed)
digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
out = ['#pragma once', '// Generated by tools/generate_mower_zh_font.py; do not edit.',
       '// Derived font: Mower UI Subset 11. Noto source under SIL OFL 1.1.',
       f'// Source SHA256: {digest}', f'// Source face index: {args.font_index}',
       '#include <stdint.h>',
       f'static const uint8_t MOWER_ZH_HEIGHT = {height};',
       f'static const uint8_t MOWER_ZH_ASCII_WIDTH = {ascii_width};',
       f'static const uint8_t MOWER_ZH_CJK_WIDTH = {cjk_width};',
       f'static const uint8_t MOWER_ZH_CJK_BITMAP_HEIGHT = {cjk_bitmap_height};',
       f'static const uint8_t MOWER_ZH_ASCII_COUNT = {ascii_count};',
       f'static const uint8_t MOWER_ZH_ASCII_BYTES = {(ascii_width * height + 7) // 8};',
       f'static const uint8_t MOWER_ZH_CJK_BYTES = {(cjk_width * cjk_bitmap_height + 7) // 8};',
       'struct MowerZhGlyph { uint16_t code; };',
       'static const MowerZhGlyph mowerZhGlyphs[] = {', *records, '};',
       'static const uint8_t mowerZhBits[] = {']
for i in range(0, len(bits), 16):
    out.append('  ' + ', '.join(f'0x{b:02X}' for b in bits[i:i+16]) + ',')
out += ['};', '']
generated = '\n'.join(out)
header = gui / 'mower_zh_font.h'
if args.check:
    assert header.read_text() == generated, f'Generated font differs from {header}'
else:
    header.write_text(generated)
print(f'PASS {len(codes)} complete glyphs; {len(bits)} bitmap bytes; '
      f'11px type / {height}px rows; source SHA256 {digest}; face {args.font_index}')
